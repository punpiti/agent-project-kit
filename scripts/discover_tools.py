#!/usr/bin/env python3
"""Find where document/PDF/OCR tools actually live on this machine.

    discover_tools.py [TOOL ...] [--json] [--write .ai/LOCAL_RESOURCES.md]

`which pandoc` failing does not mean pandoc is missing: it may exist only in a
Conda-family environment. This probes PATH, then every environment's `bin/`
(Scripts/ and Library/bin on Windows) under conda, mamba and micromamba roots,
and Python modules (pymupdf, docx, ...) per environment interpreter. Results
are absolute paths plus the environment name, so agents can call
`<path>` or `<manager> run -n <env> ...` directly.

--write replaces the marked "Tool locations" block in the given Markdown file
(appending it when absent) and leaves all other content untouched.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import shutil
import socket
import subprocess
from pathlib import Path

DEFAULT_TOOLS = ("pandoc", "xelatex", "lualatex", "pdftotext", "pdfinfo", "pdftoppm",
                 "tesseract", "qpdf", "gs", "magick", "convert", "libreoffice", "soffice",
                 "inkscape", "rsvg-convert", "ffmpeg", "mutool", "git", "gh")
DEFAULT_MODULES = ("pymupdf", "docx", "openpyxl", "pptx", "PIL", "pytesseract", "pdfplumber")
BEGIN = "<!-- BEGIN apk:tool-locations -->"
END = "<!-- END apk:tool-locations -->"


def env_roots() -> list[Path]:
    home = Path.home()
    candidates = [os.environ.get("CONDA_PREFIX"), os.environ.get("MAMBA_ROOT_PREFIX"),
                  os.environ.get("CONDA_ROOT")]
    candidates += [str(home / name) for name in
                   ("miniconda3", "anaconda3", "miniforge3", "mambaforge", "micromamba",
                    ".local/share/mamba", ".conda", "AppData/Local/miniconda3")]
    roots = []
    for item in candidates:
        if not item:
            continue
        path = Path(item)
        if path.name != "envs" and (path / "envs").is_dir():
            path = path / "envs"
        elif path.parent.name == "envs":
            path = path.parent
        if path.is_dir() and path.resolve() not in [r.resolve() for r in roots]:
            roots.append(path)
    return roots


def environments() -> dict[str, Path]:
    envs = {}
    for root in env_roots():
        for env in sorted(p for p in root.iterdir() if p.is_dir()):
            envs.setdefault(env.name, env)
    base = Path(os.environ.get("CONDA_EXE", "")).resolve().parent.parent if os.environ.get("CONDA_EXE") else None
    if base and (base / "bin").is_dir():
        envs.setdefault("base", base)
    return envs


def bin_dirs(env: Path) -> list[Path]:
    return [d for d in (env / "bin", env / "Scripts", env / "Library" / "bin") if d.is_dir()]


def manager() -> str:
    for name in ("micromamba", "mamba", "conda"):
        if shutil.which(name):
            return name
    return "conda"


def find_tools(tools, envs) -> dict[str, list[dict]]:
    found: dict[str, list[dict]] = {}
    for tool in tools:
        hits = []
        system = shutil.which(tool)
        if system:
            hits.append({"path": system, "env": None})
        for name, env in envs.items():
            for directory in bin_dirs(env):
                for candidate in (directory / tool, directory / f"{tool}.exe"):
                    if candidate.is_file() and os.access(candidate, os.X_OK):
                        if str(candidate) not in {h["path"] for h in hits}:
                            hits.append({"path": str(candidate), "env": name})
                        break
        found[tool] = hits
    return found


def find_modules(modules, envs) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {m: [] for m in modules}
    for name, env in envs.items():
        python = next((d / exe for d in bin_dirs(env) for exe in ("python", "python.exe")
                       if (d / exe).is_file()), None)
        if not python:
            continue
        code = ("import importlib.util,json,sys;"
                "print(json.dumps([m for m in sys.argv[1:] if importlib.util.find_spec(m)]))")
        try:
            out = subprocess.run([str(python), "-c", code, *modules], capture_output=True,
                                 text=True, timeout=20)
            for module in json.loads(out.stdout or "[]"):
                found[module].append(name)
        except (OSError, subprocess.TimeoutExpired, json.JSONDecodeError):
            continue
    return found


def render(tools, modules, mgr) -> str:
    lines = [BEGIN, f"## Tool locations ({socket.gethostname()}, {dt.date.today().isoformat()})", "",
             "Generated by `scripts/discover_tools.py`; rerun it instead of `find /`.",
             f"Env-only tools run as `<path>` or `{mgr} run -n <env> <tool>`.", "",
             "| Tool | Location | Env |", "|---|---|---|"]
    for tool, hits in tools.items():
        if not hits:
            lines.append(f"| {tool} | not found | — |")
        for hit in hits:
            lines.append(f"| {tool} | `{hit['path']}` | {hit['env'] or 'system PATH'} |")
    lines += ["", "| Python module | Environments |", "|---|---|"]
    for module, envs in modules.items():
        lines.append(f"| {module} | {', '.join(envs) if envs else 'not found'} |")
    lines.append(END)
    return "\n".join(lines) + "\n"


def write_block(path: Path, block: str) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = text[:start] + block.rstrip("\n") + text[end:]
    else:
        text = (text.rstrip("\n") + "\n\n" if text else "") + block
    path.write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("tools", nargs="*", help=f"tools to locate (default: {' '.join(DEFAULT_TOOLS)})")
    parser.add_argument("--modules", nargs="*", default=list(DEFAULT_MODULES))
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--write", type=Path, help="update the tool-location block in this Markdown file")
    args = parser.parse_args()
    envs = environments()
    tools = find_tools(args.tools or DEFAULT_TOOLS, envs)
    modules = find_modules(args.modules, envs) if args.modules else {}
    if args.json:
        print(json.dumps({"environments": {k: str(v) for k, v in envs.items()},
                          "tools": tools, "modules": modules}, indent=2))
    else:
        block = render(tools, modules, manager())
        if args.write:
            write_block(args.write, block)
            print(f"updated {args.write}")
        else:
            print(block, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
